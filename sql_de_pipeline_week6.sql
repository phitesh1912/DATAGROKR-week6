DROP SCHEMA IF EXISTS stg CASCADE;
DROP SCHEMA IF EXISTS dw  CASCADE;
CREATE SCHEMA stg;   -- raw landing area (UNLOGGED = faster, not crash-safe, fine for staging)
CREATE SCHEMA dw;    -- warehouse

-- =====================================================================
-- PART 1: WAREHOUSE TABLES
-- =====================================================================

-- Customer dimension: SCD Type 1 (overwrite on change) + soft delete flag
CREATE TABLE dw.dim_customer (
    customer_key  SERIAL PRIMARY KEY,
    customer_code TEXT NOT NULL UNIQUE,          -- business / natural key
    full_name     TEXT NOT NULL,
    email         TEXT,
    city          TEXT,
    segment       TEXT NOT NULL CHECK (segment IN ('Retail','Corporate','Wholesale')),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Product dimension: SCD Type 2 (keep history of price / attribute changes)
CREATE TABLE dw.dim_product (
    product_key  SERIAL PRIMARY KEY,
    sku          TEXT NOT NULL,
    product_name TEXT NOT NULL,
    category     TEXT NOT NULL,
    brand        TEXT NOT NULL,
    list_price   NUMERIC(10,2) NOT NULL,
    valid_from   DATE NOT NULL,
    valid_to     DATE NOT NULL DEFAULT DATE '9999-12-31',
    is_current   BOOLEAN NOT NULL DEFAULT TRUE
);
-- PARTIAL UNIQUE INDEX: only one *current* row per SKU (history rows may repeat the SKU)
CREATE UNIQUE INDEX uq_dim_product_current_sku ON dw.dim_product (sku) WHERE is_current;

CREATE TABLE dw.dim_store (
    store_key  SERIAL PRIMARY KEY,
    store_code TEXT NOT NULL UNIQUE,
    store_name TEXT NOT NULL,
    city       TEXT NOT NULL,
    region     TEXT NOT NULL
);

-- Fact table: RANGE partitioned by order_date (one partition per month)
-- NOTE: in a partitioned table every PK/UNIQUE constraint must include the partition key.
CREATE TABLE dw.fact_orders (
    order_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_ref    TEXT    NOT NULL,
    order_date   DATE    NOT NULL,
    customer_key INT     NOT NULL REFERENCES dw.dim_customer(customer_key),
    product_key  INT     NOT NULL REFERENCES dw.dim_product(product_key),
    store_key    INT     NOT NULL REFERENCES dw.dim_store(store_key),
    quantity     INT     NOT NULL CHECK (quantity > 0),
    unit_price   NUMERIC(10,2) NOT NULL,
    total_amount NUMERIC(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    status       TEXT    NOT NULL CHECK (status IN ('PENDING','SHIPPED','DELIVERED','CANCELLED','RETURNED')),
    PRIMARY KEY (order_id, order_date),
    UNIQUE (order_ref, order_date)               -- makes re-runs idempotent (ON CONFLICT DO NOTHING)
) PARTITION BY RANGE (order_date);

-- Monthly partitions 2025-12 .. 2026-12 created in a loop
DO $$
DECLARE m DATE := DATE '2025-12-01';
BEGIN
    WHILE m <= DATE '2026-12-01' LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS dw.%I PARTITION OF dw.fact_orders FOR VALUES FROM (%L) TO (%L)',
            'fact_orders_' || to_char(m, 'YYYY_MM'), m, (m + INTERVAL '1 month')::DATE);
        m := (m + INTERVAL '1 month')::DATE;
    END LOOP;
END $$;

-- Safety net: catches any date outside the defined ranges
CREATE TABLE dw.fact_orders_default PARTITION OF dw.fact_orders DEFAULT;

-- Pipeline audit log
CREATE TABLE dw.etl_run_log (
    run_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name      TEXT NOT NULL,
    started_at    TIMESTAMPTZ NOT NULL,
    finished_at   TIMESTAMPTZ,
    rows_read     INT,
    rows_loaded   INT,
    rows_rejected INT,
    status        TEXT NOT NULL
);

-- Staging tables (UNLOGGED, no constraints, no indexes = fastest COPY target)
CREATE UNLOGGED TABLE stg.customer_updates (
    customer_code TEXT, full_name TEXT, email TEXT, city TEXT, segment TEXT
);
CREATE UNLOGGED TABLE stg.product_updates (
    sku TEXT, product_name TEXT, category TEXT, brand TEXT, list_price NUMERIC(10,2)
);
CREATE UNLOGGED TABLE stg.orders (
    order_ref TEXT, order_date DATE, customer_code TEXT, product_sku TEXT,
    store_code TEXT, quantity INT, unit_price NUMERIC(10,2), status TEXT
);
CREATE UNLOGGED TABLE stg.rejected_orders (
    order_ref TEXT, order_date DATE, customer_code TEXT, product_sku TEXT,
    store_code TEXT, quantity INT, unit_price NUMERIC(10,2), status TEXT,
    reject_reason TEXT
);

