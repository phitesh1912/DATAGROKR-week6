-- =====================================================================
-- PART 4: THE PIPELINE - MERGE on dimension tables
--   Step A  MERGE customers  (SCD Type 1: update in place / insert new)
--   Step B  soft-deactivate customers missing from the feed
--   Step C  MERGE products   (SCD Type 2 step 1: expire changed rows, insert new SKUs)
--   Step D  insert the new version of every product that was just expired
--   Step E  validate orders -> rejects table
--   Step F  load facts (idempotent), then write the audit row
-- =====================================================================

CREATE OR REPLACE PROCEDURE dw.run_pipeline()
LANGUAGE plpgsql
AS $$
DECLARE
    v_start    TIMESTAMPTZ := clock_timestamp();
    n          INT;
    v_cust     INT := 0;
    v_deact    INT := 0;
    v_prod_exp INT := 0;
    v_prod_new INT := 0;
    v_read     INT := 0;
    v_loaded   INT := 0;
    v_rej      INT := 0;
BEGIN
    -- A) SCD1 MERGE ---------------------------------------------------
    MERGE INTO dw.dim_customer AS t
    USING stg.customer_updates AS s
       ON t.customer_code = s.customer_code
    WHEN MATCHED AND (t.full_name, t.email, t.city, t.segment, t.is_active)
                     IS DISTINCT FROM (s.full_name, s.email, s.city, s.segment, TRUE) THEN
        UPDATE SET full_name  = s.full_name,
                   email      = s.email,
                   city       = s.city,
                   segment    = s.segment,
                   is_active  = TRUE,
                   updated_at = now()
    WHEN NOT MATCHED THEN
        INSERT (customer_code, full_name, email, city, segment)
        VALUES (s.customer_code, s.full_name, s.email, s.city, s.segment);
    GET DIAGNOSTICS v_cust = ROW_COUNT;

    -- B) Soft delete (works on every version).
    --    PG17 alternative inside the MERGE above:
    --      WHEN NOT MATCHED BY SOURCE AND t.is_active THEN UPDATE SET is_active = FALSE, updated_at = now()
    UPDATE dw.dim_customer d
       SET is_active = FALSE, updated_at = now()
     WHERE d.is_active
       AND NOT EXISTS (SELECT 1 FROM stg.customer_updates s WHERE s.customer_code = d.customer_code);
    GET DIAGNOSTICS v_deact = ROW_COUNT;

    -- C) SCD2 step 1: expire changed current rows, insert unseen SKUs -------
    MERGE INTO dw.dim_product AS t
    USING stg.product_updates AS s
       ON t.sku = s.sku AND t.is_current
    WHEN MATCHED AND (t.product_name, t.category, t.brand, t.list_price)
                     IS DISTINCT FROM (s.product_name, s.category, s.brand, s.list_price) THEN
        UPDATE SET valid_to = CURRENT_DATE - 1, is_current = FALSE
    WHEN NOT MATCHED THEN
        INSERT (sku, product_name, category, brand, list_price, valid_from)
        VALUES (s.sku, s.product_name, s.category, s.brand, s.list_price, CURRENT_DATE);
    GET DIAGNOSTICS n = ROW_COUNT;

    -- D) SCD2 step 2: every staged SKU that now has NO current row gets a new version
    INSERT INTO dw.dim_product (sku, product_name, category, brand, list_price, valid_from)
    SELECT s.sku, s.product_name, s.category, s.brand, s.list_price, CURRENT_DATE
      FROM stg.product_updates s
     WHERE NOT EXISTS (SELECT 1 FROM dw.dim_product p WHERE p.sku = s.sku AND p.is_current);
    GET DIAGNOSTICS v_prod_exp = ROW_COUNT;     -- number of new versions created
    v_prod_new := n - v_prod_exp;               -- MERGE touched rows = expired + brand-new

    -- E) Validation: anything that cannot be loaded goes to rejects ----------
    TRUNCATE stg.rejected_orders;
    INSERT INTO stg.rejected_orders
    SELECT order_ref, order_date, customer_code, product_sku, store_code,
           quantity, unit_price, status, reject_reason
      FROM (
        SELECT o.*,
               CASE
                 WHEN o.quantity IS NULL OR o.quantity <= 0 THEN 'invalid quantity'
                 WHEN NOT EXISTS (SELECT 1 FROM dw.dim_customer c WHERE c.customer_code = o.customer_code) THEN 'unknown customer'
                 WHEN NOT EXISTS (SELECT 1 FROM dw.dim_product  p WHERE p.sku = o.product_sku AND p.is_current) THEN 'unknown product'
                 WHEN NOT EXISTS (SELECT 1 FROM dw.dim_store    s WHERE s.store_code = o.store_code) THEN 'unknown store'
               END AS reject_reason
          FROM stg.orders o
      ) x
     WHERE reject_reason IS NOT NULL;
    GET DIAGNOSTICS v_rej = ROW_COUNT;

    -- F) Fact load: surrogate-key lookups, idempotent via ON CONFLICT ---------
    INSERT INTO dw.fact_orders (order_ref, order_date, customer_key, product_key, store_key,
                                quantity, unit_price, status)
    SELECT o.order_ref, o.order_date, c.customer_key, p.product_key, s.store_key,
           o.quantity, o.unit_price, o.status
      FROM stg.orders o
      JOIN dw.dim_customer c ON c.customer_code = o.customer_code
      JOIN dw.dim_product  p ON p.sku = o.product_sku AND p.is_current
      JOIN dw.dim_store    s ON s.store_code = o.store_code
     WHERE o.quantity > 0
    ON CONFLICT (order_ref, order_date) DO NOTHING;
    GET DIAGNOSTICS v_loaded = ROW_COUNT;

    SELECT COUNT(*) INTO v_read FROM stg.orders;

    INSERT INTO dw.etl_run_log (job_name, started_at, finished_at, rows_read, rows_loaded, rows_rejected, status)
    VALUES ('run_pipeline', v_start, clock_timestamp(), v_read, v_loaded, v_rej, 'SUCCESS');

    RAISE NOTICE 'customers merged=% deactivated=% | products expired/new versions=% new skus=% | orders read=% loaded=% rejected=%',
                 v_cust, v_deact, v_prod_exp, v_prod_new, v_read, v_loaded, v_rej;
END $$;

-- BEFORE snapshot
SELECT 'customers' AS tbl, COUNT(*) AS total, COUNT(*) FILTER (WHERE is_active) AS active FROM dw.dim_customer
UNION ALL
SELECT 'products',  COUNT(*), COUNT(*) FILTER (WHERE is_current) FROM dw.dim_product
UNION ALL
SELECT 'fact_orders', COUNT(*), NULL FROM dw.fact_orders;

CALL dw.run_pipeline();

-- AFTER snapshot (expect: customers 30/24 active, products 34/26 current, fact_orders 67)
SELECT 'customers' AS tbl, COUNT(*) AS total, COUNT(*) FILTER (WHERE is_active) AS active FROM dw.dim_customer
UNION ALL
SELECT 'products',  COUNT(*), COUNT(*) FILTER (WHERE is_current) FROM dw.dim_product
UNION ALL
SELECT 'fact_orders', COUNT(*), NULL FROM dw.fact_orders;

-- Idempotency check: second run changes nothing (0 merged, 0 new versions, 0 new facts)
CALL dw.run_pipeline();

-- What did the MERGE change?
SELECT customer_code, full_name, city, segment, is_active, updated_at > created_at AS was_updated
FROM dw.dim_customer
ORDER BY customer_code;

-- SCD2 history: products with more than one version
SELECT sku, product_name, list_price, valid_from, valid_to, is_current
FROM dw.dim_product
WHERE sku IN (SELECT sku FROM dw.dim_product GROUP BY sku HAVING COUNT(*) > 1)
ORDER BY sku, valid_from;

-- Rejected rows and why
SELECT * FROM stg.rejected_orders;

-- =====================================================================
-- PART 5: RANGE PARTITIONING - inspect, prune, maintain
-- =====================================================================

-- 5.1 Rows per partition (tableoid tells which child table stores the row)
SELECT tableoid::regclass AS partition_name, COUNT(*) AS row_count,
       MIN(order_date) AS min_date, MAX(order_date) AS max_date
FROM dw.fact_orders
GROUP BY 1
ORDER BY 1;

-- 5.2 Partition pruning: only the May and June partitions are scanned
EXPLAIN (COSTS OFF)
SELECT SUM(total_amount)
FROM dw.fact_orders
WHERE order_date >= DATE '2026-05-01' AND order_date < DATE '2026-07-01';

-- 5.3 Pruning is lost when the partition key is wrapped in a function (all partitions scanned)
EXPLAIN (COSTS OFF)
SELECT SUM(total_amount)
FROM dw.fact_orders
WHERE EXTRACT(MONTH FROM order_date) = 5;
-- Fix: always filter with a raw range on order_date (as in 5.2)

-- 5.4 Show the partition bounds
SELECT c.relname AS partition_name, pg_get_expr(c.relpartbound, c.oid) AS bounds
FROM pg_class p
JOIN pg_inherits i ON i.inhparent = p.oid
JOIN pg_class c    ON c.oid = i.inhrelid
WHERE p.oid = 'dw.fact_orders'::regclass
ORDER BY c.relname;

-- 5.5 Add the 2027-01 partition. The DEFAULT partition already holds a January-2027 row
--     (ORD-1069), so creating the partition directly would fail. Safe pattern:
BEGIN;
ALTER TABLE dw.fact_orders DETACH PARTITION dw.fact_orders_default;

CREATE TABLE dw.fact_orders_2027_01 PARTITION OF dw.fact_orders
    FOR VALUES FROM ('2027-01-01') TO ('2027-02-01');

INSERT INTO dw.fact_orders (order_id, order_ref, order_date, customer_key, product_key, store_key,
                            quantity, unit_price, status)
SELECT order_id, order_ref, order_date, customer_key, product_key, store_key,
       quantity, unit_price, status
FROM dw.fact_orders_default
WHERE order_date >= DATE '2027-01-01' AND order_date < DATE '2027-02-01';

DELETE FROM dw.fact_orders_default
WHERE order_date >= DATE '2027-01-01' AND order_date < DATE '2027-02-01';

ALTER TABLE dw.fact_orders ATTACH PARTITION dw.fact_orders_default DEFAULT;
COMMIT;

SELECT tableoid::regclass AS partition_name, COUNT(*) FROM dw.fact_orders
WHERE order_date >= DATE '2027-01-01' GROUP BY 1;

-- 5.6 Retention / archiving: detach the oldest partition in one fast metadata operation
--     (DETACH ... CONCURRENTLY exists too, but cannot run inside a transaction block)
ALTER TABLE dw.fact_orders DETACH PARTITION dw.fact_orders_2025_12;
ALTER TABLE dw.fact_orders_2025_12 RENAME TO fact_orders_archive_2025_12;
-- Export then drop when you are done with it:
--   COPY dw.fact_orders_archive_2025_12 TO '/tmp/fact_orders_2025_12.csv' WITH (FORMAT csv, HEADER true);
--   DROP TABLE dw.fact_orders_archive_2025_12;

-- =====================================================================
-- PART 6: COPY - export and bulk-load best practices
-- =====================================================================

-- 6.1 Export a query result as CSV (to the client console; use \copy ... TO 'file' from psql for a file)
COPY (
    SELECT o.order_ref, o.order_date, c.full_name, p.product_name, o.quantity, o.total_amount, o.status
    FROM dw.fact_orders o
    JOIN dw.dim_customer c ON c.customer_key = o.customer_key
    JOIN dw.dim_product  p ON p.product_key  = o.product_key
    WHERE o.status = 'PENDING'
    ORDER BY o.order_date
) TO STDOUT WITH (FORMAT csv, HEADER true);

-- 6.2 Loading from a real file instead of inline data:
--   Client-side file (works anywhere, no superuser):
--     \copy stg.orders FROM 'orders_2026_10_14.csv' WITH (FORMAT csv, HEADER true)
--   Server-side file (needs pg_read_server_files role and the file on the DB server):
--     COPY stg.orders FROM '/var/lib/postgresql/import/orders_2026_10_14.csv' WITH (FORMAT csv, HEADER true);

-- 6.3 Bulk-load checklist (what this script already does):
--   * load into UNLOGGED staging tables with no indexes or constraints
--   * COPY instead of row-by-row INSERT
--   * validate and reject in SQL AFTER the load, instead of failing the whole COPY
--   * create secondary indexes AFTER the big load (Part 7) and then ANALYZE
--   * for a huge first load into an empty table in the same transaction:
--       BEGIN; TRUNCATE t; COPY t FROM ... WITH (FREEZE);  COMMIT;

-- =====================================================================
-- PART 7: COMPOSITE & PARTIAL INDEXES (created after the load)
-- Indexes created on a partitioned parent are created on every partition automatically.
-- =====================================================================

-- 7.1 COMPOSITE: "orders of a customer in a date range, newest first"
--     Column order matters: equality column first, range / sort column second.
CREATE INDEX idx_fact_customer_date ON dw.fact_orders (customer_key, order_date DESC);

-- 7.2 COMPOSITE: product + store drill-down over time
CREATE INDEX idx_fact_prod_store_date ON dw.fact_orders (product_key, store_key, order_date);

-- 7.3 PARTIAL: only open orders are queried by operations, and they are a small slice of the table
CREATE INDEX idx_fact_pending ON dw.fact_orders (order_date, customer_key) WHERE status = 'PENDING';

-- 7.4 PARTIAL + COVERING (INCLUDE): returns / cancellations report served from the index alone
CREATE INDEX idx_fact_problem_orders ON dw.fact_orders (order_date)
    INCLUDE (customer_key, total_amount)
    WHERE status IN ('CANCELLED','RETURNED');

-- 7.5 PARTIAL on a dimension: active customers by city
CREATE INDEX idx_dim_customer_active_city ON dw.dim_customer (city, segment) WHERE is_active;

ANALYZE dw.fact_orders;
ANALYZE dw.dim_customer;
ANALYZE dw.dim_product;

-- The tables are tiny, so the planner would prefer a sequential scan.
-- Discourage it to see which index each query WOULD use on a big table.
SET enable_seqscan = off;

-- 7.6 Composite index used (leading column + range on the second column)
EXPLAIN (COSTS OFF)
SELECT order_ref, order_date, total_amount
FROM dw.fact_orders
WHERE customer_key = 1 AND order_date >= DATE '2026-01-01'
ORDER BY order_date DESC;

-- 7.7 Composite index NOT usable when the leading column is missing (filter on order_date only)
--     -> falls back to partition pruning + scans; add a different index if this query is hot
EXPLAIN (COSTS OFF)
SELECT COUNT(*) FROM dw.fact_orders WHERE order_date = DATE '2026-05-20';

-- 7.8 Partial index used: the WHERE clause implies the index predicate
EXPLAIN (COSTS OFF)
SELECT order_date, customer_key FROM dw.fact_orders
WHERE status = 'PENDING' AND order_date >= DATE '2026-09-01';

-- 7.9 Partial index NOT used: different status than the predicate
EXPLAIN (COSTS OFF)
SELECT order_date, customer_key FROM dw.fact_orders
WHERE status = 'SHIPPED' AND order_date >= DATE '2026-09-01';

-- 7.10 Index-only scan candidate from the covering partial index
EXPLAIN (COSTS OFF)
SELECT order_date, customer_key, total_amount FROM dw.fact_orders
WHERE status IN ('CANCELLED','RETURNED') AND order_date >= DATE '2026-01-01';

RESET enable_seqscan;

-- 7.11 Index housekeeping: which indexes exist, how big, and are they used?
SELECT s.relname AS table_name, s.indexrelname AS index_name,
       pg_size_pretty(pg_relation_size(s.indexrelid)) AS size,
       s.idx_scan AS times_used
FROM pg_stat_user_indexes s
WHERE s.schemaname = 'dw'
ORDER BY pg_relation_size(s.indexrelid) DESC
LIMIT 20;

-- =====================================================================
-- PART 8: REPORTS ON THE FINISHED WAREHOUSE
-- =====================================================================

-- 8.1 Monthly revenue by region (partition pruned by date range)
SELECT to_char(o.order_date, 'YYYY-MM') AS month, st.region,
       SUM(o.total_amount) AS revenue, COUNT(*) AS orders
FROM dw.fact_orders o
JOIN dw.dim_store st ON st.store_key = o.store_key
WHERE o.order_date >= DATE '2026-01-01' AND o.order_date < DATE '2026-11-01'
  AND o.status NOT IN ('CANCELLED','RETURNED')
GROUP BY 1, 2
ORDER BY 1, 2;

-- 8.2 Price history impact: revenue at the version of the price that was current when sold
--     (point-in-time join against the SCD2 validity window)
SELECT p.sku, p.product_name, p.list_price AS list_price_version, p.valid_from, p.valid_to,
       COUNT(*) AS orders_in_window
FROM dw.dim_product p
JOIN dw.fact_orders o ON o.product_key = p.product_key
GROUP BY p.sku, p.product_name, p.list_price, p.valid_from, p.valid_to
ORDER BY p.sku, p.valid_from;

-- 8.3 Customers deactivated by the feed and their lifetime spend
SELECT c.customer_code, c.full_name, c.city, SUM(o.total_amount) AS lifetime_spend
FROM dw.dim_customer c
LEFT JOIN dw.fact_orders o ON o.customer_key = c.customer_key
WHERE NOT c.is_active
GROUP BY c.customer_code, c.full_name, c.city
ORDER BY lifetime_spend DESC NULLS LAST;

-- 8.4 Pipeline health from the audit log
SELECT job_name, status, COUNT(*) AS runs,
       SUM(rows_read) AS rows_read, SUM(rows_loaded) AS rows_loaded, SUM(rows_rejected) AS rows_rejected,
       ROUND(AVG(EXTRACT(EPOCH FROM (finished_at - started_at)))::NUMERIC, 1) AS avg_seconds
FROM dw.etl_run_log
GROUP BY job_name, status
ORDER BY job_name, status;

